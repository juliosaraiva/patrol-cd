/**
 * ApplicationSet mutations and derived queries (API-118, ASET-124..126) that are not in
 * src/api/queries: generate (dry run), delete, and the Applications an ApplicationSet owns.
 */
import { useMutation, useQueryClient } from '@tanstack/react-query';
import { useMemo } from 'react';
import * as appsets from '../endpoints/applicationsets';
import { useApplications } from '../queries/applications';
import { canonicalNamespace, controlPlaneNamespace, queryKeys } from '../queries/keys';
import type { Application, ApplicationSet } from '../types';

/** POST /applicationsets/generate: renders the Applications a spec would produce. Never persisted. */
export function useGenerateApplicationSet() {
  return useMutation({
    mutationFn: (applicationSet: ApplicationSet) => appsets.generateApplicationSet({ applicationSet }),
  });
}

/** DELETE /applicationsets/{name}; refreshes lists and drops the cached details. */
export function useDeleteApplicationSet() {
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: ({ name, namespace }: { name: string; namespace?: string }) =>
      appsets.deleteApplicationSet(name, canonicalNamespace(namespace, controlPlaneNamespace(queryClient))),
    onSuccess: (_r, { name, namespace }) => {
      queryClient.removeQueries({
        queryKey: queryKeys.applicationSets.detail(name, canonicalNamespace(namespace, controlPlaneNamespace(queryClient))),
      });
      return queryClient.invalidateQueries({ queryKey: queryKeys.applicationSets.lists() });
    },
  });
}

/** True when `app` has an ownerReference to the ApplicationSet. */
export function isOwnedBy(app: Application, set: ApplicationSet): boolean {
  const owners = app.metadata.ownerReferences ?? [];
  const sameNamespace = (app.metadata.namespace ?? '') === (set.metadata.namespace ?? '') || !set.metadata.namespace;
  return (
    sameNamespace &&
    owners.some(
      (ref) => ref.kind === 'ApplicationSet' && ref.name === set.metadata.name && (!set.metadata.uid || !ref.uid || ref.uid === set.metadata.uid),
    )
  );
}

/**
 * Live Applications generated by `set` (ownerReferences), from the shared watched application
 * list, so health and sync update without polling.
 */
export function useApplicationSetApplications(set: ApplicationSet | undefined) {
  const query = useApplications({}, { enabled: set !== undefined });
  const owned = useMemo(() => (set ? (query.data?.items ?? []).filter((app) => isOwnedBy(app, set)) : []), [query.data, set]);
  return { ...query, owned };
}
