import { Link } from 'react-router';
import type { ApplicationSet } from '../../api/types';
import { HealthStatus, KeyValueList, Mono, SyncStatus, Table, type Column } from '../../design';
import { IconExternal } from '../../design/icons';
import { isHttpURL } from '../../lib/url';
import { applicationPath, type GeneratedAppRow } from './model';
import { previewCleanupPolicy, previewEnvironment, pullRequestSources, type PreviewEnvironment } from './previews';
import styles from './ApplicationSets.module.css';

type Row = GeneratedAppRow & { pr: PreviewEnvironment };

/**
 * Preview environments generated by pull-request generators: one row per Application with the
 * pull request number, branch, head commit, link and status, plus the cleanup policy.
 */
export function PreviewEnvironments({
  set,
  rows,
  controlPlaneNamespace,
}: {
  set: ApplicationSet;
  rows: GeneratedAppRow[];
  controlPlaneNamespace: string | undefined;
}) {
  const sources = pullRequestSources(set);
  const source = sources.length === 1 ? sources[0] : undefined;
  const data: Row[] = rows.map((r) => ({
    ...r,
    pr: previewEnvironment(r.app ?? { metadata: { name: r.name } }, source),
  }));
  const columns: Column<Row>[] = [
    {
      id: 'pr',
      header: 'Pull request',
      sortValue: (r) => Number(r.pr.number ?? Number.MAX_SAFE_INTEGER),
      cell: (r) =>
        r.pr.number ? (
          r.pr.url && isHttpURL(r.pr.url) ? (
            <a className={styles.prLink} href={r.pr.url} target="_blank" rel="noopener noreferrer">
              {`#${r.pr.number}`}
              <IconExternal />
              <span className="sr-only"> (opens in a new tab)</span>
            </a>
          ) : (
            `#${r.pr.number}`
          )
        ) : (
          <span className={styles.secondary}>Unknown</span>
        ),
    },
    { id: 'branch', header: 'Branch', sortValue: (r) => r.pr.branch, cell: (r) => (r.pr.branch ? <Mono>{r.pr.branch}</Mono> : '—') },
    {
      id: 'sha',
      header: 'Head commit',
      cell: (r) => (r.pr.headSha ? <Mono title={r.pr.headSha}>{r.pr.headSha.slice(0, 8)}</Mono> : '—'),
    },
    {
      id: 'app',
      header: 'Application',
      sortValue: (r) => r.name,
      cell: (r) => (
        <Link to={applicationPath(r.name, r.namespace, controlPlaneNamespace)}>
          <Mono>{r.name}</Mono>
        </Link>
      ),
    },
    { id: 'health', header: 'Health', sortValue: (r) => r.health, cell: (r) => <HealthStatus status={r.health} /> },
    { id: 'sync', header: 'Sync', sortValue: (r) => r.sync, cell: (r) => <SyncStatus status={r.sync} /> },
  ];
  return (
    <div className={styles.stack}>
      <KeyValueList
        items={[
          ...sources.map((s, i) => ({
            key: `source-${i}`,
            label: sources.length > 1 ? `Source ${i + 1}` : 'Source',
            value: (
              <>
                {s.provider} {s.repository ? <Mono>{s.repository}</Mono> : null}
                {s.labels.length > 0 ? `, labels ${s.labels.join(', ')}` : ''}
                {s.filters.length > 0 ? `, ${s.filters.join(' | ')}` : ''}
                {`, checked every ${s.requeueAfterSeconds} s`}
              </>
            ),
          })),
          { key: 'cleanup', label: 'Cleanup', value: previewCleanupPolicy(set) },
        ]}
      />
      <Table
        caption="Preview environments"
        columns={columns}
        rows={data}
        getRowKey={(r) => r.key}
        getRowLabel={(r) => (r.pr.number ? `Pull request ${r.pr.number}` : r.name)}
        defaultSort={{ columnId: 'pr', direction: 'ascending' }}
        empty="No open pull requests match the generator, so there are no preview environments. Open a pull request (with the required labels) to create one."
      />
      <p className={styles.muted}>
        Pull request details come from the Application labels and annotations (keys such as <Mono>pr-number</Mono>, <Mono>branch</Mono>,{' '}
        <Mono>head-sha</Mono>), its name and its source revision. Copy <Mono>{'{{number}}'}</Mono>, <Mono>{'{{branch}}'}</Mono> and{' '}
        <Mono>{'{{head_sha}}'}</Mono> into the template labels or annotations to fill every column.
      </p>
    </div>
  );
}
