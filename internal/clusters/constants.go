package clusters

import (
	"strings"

	v1alpha1 "github.com/juliosaraiva/patrol-cd/api/v1alpha1"
)

const (
	// InClusterName is the name of the synthetic in-cluster cluster (Argo CD's
	// KubernetesInClusterName). api/v1alpha1 declares only the server address.
	InClusterName = "in-cluster"
	// InClusterServer is the server URL of the in-cluster destination.
	InClusterServer = v1alpha1.KubernetesInternalAPIServerAddr

	// SettingInClusterEnabled is the patrol-cm key that enables the in-cluster cluster.
	SettingInClusterEnabled = "cluster.inClusterEnabled"

	// EnvFakeInCluster makes RestConfig use the local kubeconfig for the in-cluster server
	// (upstream ARGOCD_FAKE_IN_CLUSTER, for development only).
	EnvFakeInCluster = "PATROL_FAKE_IN_CLUSTER"

	// ExecCredentialAPIVersion is the ExecCredential version used by the k8s-auth helpers.
	ExecCredentialAPIVersion = "client.authentication.k8s.io/v1beta1"

	// DefaultK8sAuthCommand is the binary that serves `k8s-auth` in exec configurations
	// generated by RestConfig when AWS authentication runs in exec mode.
	DefaultK8sAuthCommand = "patrolcd"
	// K8sAuthSubcommand is the patrolcd subcommand that prints ExecCredentials.
	K8sAuthSubcommand = "k8s-auth"
	// upstreamK8sAuthCommand is Argo CD's helper binary. Exec configurations naming it are
	// recognized so migrated Clusters authenticate in-process.
	upstreamK8sAuthCommand = "argocd-k8s-auth"
)

// NormalizeServer returns the server URL with trailing slashes removed, the form servers are
// compared and indexed in (upstream trims "/" on write and on lookup).
func NormalizeServer(server string) string {
	return strings.TrimRight(server, "/")
}

// IsInClusterServer reports whether server is the in-cluster API server address.
func IsInClusterServer(server string) bool {
	return NormalizeServer(server) == InClusterServer
}

// InClusterEnabled reports whether the in-cluster cluster is enabled for the given patrol-cm
// data. As upstream, it is enabled unless the value is exactly "false", including when the key
// is absent or the ConfigMap could not be read (nil data).
func InClusterEnabled(settings map[string]string) bool {
	return settings[SettingInClusterEnabled] != "false"
}
