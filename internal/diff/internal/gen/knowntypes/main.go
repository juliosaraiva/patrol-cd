// Command knowntypes generates the table of Kubernetes API types that can be named in
// knownTypeFields (e.g. "core/v1/PodSpec"). Every exported struct or map type of the given
// k8s.io/api package is listed, which is the set the baseline supports.
//
//	go run ./internal/diff/internal/gen/knowntypes -alias corev1 -pkg k8s.io/api/core/v1 \
//	  -out internal/diff/knowntypes_corev1.go -docs internal/diff/testdata/known_types.txt
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"go/importer"
	"go/token"
	"go/types"
	"log/slog"
	"os"
	"sort"
	"strings"
)

const apiPrefix = "k8s.io/api/"

func main() {
	alias := flag.String("alias", "corev1", "import alias")
	pkgPath := flag.String("pkg", "k8s.io/api/core/v1", "package to scan")
	out := flag.String("out", "internal/diff/knowntypes_corev1.go", "generated Go file")
	docs := flag.String("docs", "", "optional list of supported type names")
	flag.Parse()
	if err := run(*alias, *pkgPath, *out, *docs); err != nil {
		slog.Error("generate known types", "error", err)
		os.Exit(1)
	}
}

func run(alias, pkgPath, out, docs string) error {
	if !strings.HasPrefix(pkgPath, apiPrefix) {
		return fmt.Errorf("package must be under %s", apiPrefix)
	}
	pkg, err := importer.ForCompiler(token.NewFileSet(), "source", nil).Import(pkgPath)
	if err != nil {
		return fmt.Errorf("import %s: %w", pkgPath, err)
	}
	short := strings.TrimPrefix(pkgPath, apiPrefix)
	var names []string
	for _, n := range pkg.Scope().Names() {
		tn, ok := pkg.Scope().Lookup(n).(*types.TypeName)
		if !ok || !tn.Exported() {
			continue
		}
		switch tn.Type().Underlying().(type) {
		case *types.Struct, *types.Map:
			names = append(names, n)
		}
	}
	sort.Strings(names)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/diff/internal/gen/knowntypes. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package diff\n\nimport %s %q\n\n", alias, pkgPath)
	fmt.Fprintf(&b, "func init() {\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\tknownTypes[%q] = func() any { return &%s.%s{} }\n", short+"/"+n, alias, n)
	}
	fmt.Fprintf(&b, "}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format generated code: %w", err)
	}
	if err := os.WriteFile(out, src, 0o644); err != nil { //nolint:gosec // generated source checked into the repository
		return fmt.Errorf("write %s: %w", out, err)
	}
	if docs != "" {
		list := make([]string, len(names))
		for i, n := range names {
			list[i] = short + "/" + n
		}
		if err := os.WriteFile(docs, []byte(strings.Join(list, "\n")+"\n"), 0o644); err != nil { //nolint:gosec // see above
			return fmt.Errorf("write %s: %w", docs, err)
		}
	}
	return nil
}
