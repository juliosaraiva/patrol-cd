func TestImportRefusesForeignGroups(t *testing.T) {
	ctx := requireEnv(t)
	ns := newNamespace(t, ctx, "foreign")
	tio := newTestIO(ns)
	dir := t.TempDir()
	argo := filepath.Join(dir, "argo.yaml")
	require.NoError(t, os.WriteFile(argo, []byte("apiVersion: argoproj.io/v1alpha1\nkind: Application\nmetadata:\n  name: a\nspec: {}\n"), 0o600))
	err := tio.run(ctx, "admin", "import", argo)
	require.Error(t, err)
	assert.Contains(t, err.Error(), "patrol admin argocd-import")

	old := filepath.Join(dir, "old.yaml")
	require.NoError(t, os.WriteFile(old, []byte(`apiVersion: `+oldGroup+`/v1alpha1
kind: AppProject
metadata:
  name: migrated
  annotations:
    notifications.`+oldGroup+`/subscribe.on-sync-failed.slack: team
  finalizers: [resources-finalizer.`+oldGroup+`]
spec:
  clusterResourceWhitelist:
    - group: `+oldGroup+`
      kind: Application
`), 0o600))
	err = tio.run(ctx, "admin", "import", old)
	require.Error(t, err)
	assert.Contains(t, err.Error(), "--migrate-group")
	_, err = envDyn.Resource(kindAppProject.gvr(currentGroup)).Namespace(ns).Get(ctx, "migrated", metav1.GetOptions{})
	assert.True(t, apierrors.IsNotFound(err), "nothing written when refused")

	// The import fails on missing settings? No: ConfigMaps are optional on import.
	require.NoError(t, tio.run(ctx, "admin", "import", "--migrate-group", old))
	proj, err := envDyn.Resource(kindAppProject.gvr(currentGroup)).Namespace(ns).Get(ctx, "migrated", metav1.GetOptions{})
	require.NoError(t, err)
	assert.Equal(t, []string{"resources-finalizer." + currentGroup}, proj.GetFinalizers())
	assert.Contains(t, proj.GetAnnotations(), "notifications."+currentGroup+"/subscribe.on-sync-failed.slack")
	wl, _, _ := unstructured.NestedSlice(proj.Object, "spec", "clusterResourceWhitelist")
	require.Len(t, wl, 1)
	assert.Equal(t, currentGroup, wl[0].(map[string]any)["group"])
	_, _ = envDyn.Resource(kindAppProject.gvr(currentGroup)).Namespace(ns).Patch(ctx, "migrated", types.MergePatchType, []byte(`{"metadata":{"finalizers":null}}`), metav1.PatchOptions{})
}

