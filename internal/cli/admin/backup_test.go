func TestSplitObjectsAndSpecsEqual(t *testing.T) {
	t.Parallel()
	objs, err := splitObjects([]byte(`---
apiVersion: v1
kind: List
items:
- apiVersion: v1
  kind: ConfigMap
  metadata: {name: a}
  data: {k: v}
---
# comment only
---
apiVersion: cd.patrol.example/v1alpha1
kind: Application
metadata: {name: b}
spec:
  revisionHistoryLimit: 9007199254740993
`))
	require.NoError(t, err)
	require.Len(t, objs, 2)
	v, _, _ := unstructured.NestedInt64(objs[1].Object, "spec", "revisionHistoryLimit")
	assert.Equal(t, int64(9007199254740993), v, "large integers keep their precision")

	_, err = splitObjects([]byte("kind: ConfigMap\nmetadata: {name: x}\n"))
	require.Error(t, err)

	a := &unstructured.Unstructured{Object: map[string]any{"kind": "AppProject", "spec": map[string]any{"n": int64(1)}, "metadata": map[string]any{"annotations": map[string]any{corev1.LastAppliedConfigAnnotation: "x"}}}}
	b := &unstructured.Unstructured{Object: map[string]any{"kind": "AppProject", "spec": map[string]any{"n": float64(1)}}}
	assert.True(t, specsEqual(a, b), "number types and last-applied are ignored")
	b.Object["spec"] = map[string]any{"n": float64(2)}
	assert.False(t, specsEqual(a, b))
}

func TestIsPatrolSecret(t *testing.T) {
	t.Parallel()
	mk := func(name, typ string, labels, annotations map[string]string) *unstructured.Unstructured {
		u := &unstructured.Unstructured{Object: map[string]any{"apiVersion": "v1", "kind": "Secret", "type": typ}}
		u.SetName(name)
		u.SetLabels(labels)
		u.SetAnnotations(annotations)
		return u
	}
	ref := map[string]bool{"oidc": true}
	cases := []struct {
		obj  *unstructured.Unstructured
		want bool
	}{
		{mk("patrol-secret", "Opaque", nil, nil), true},
		{mk("patrol-notifications-secret", "Opaque", nil, nil), true},
		{mk("repo", "Opaque", map[string]string{"cd.patrol.example/secret-type": "repository"}, nil), true},
		{mk("managed", "Opaque", nil, map[string]string{"cd.patrol.example/managed-by": "patrol-cd"}), true},
		{mk("oidc", "Opaque", nil, nil), true},
		{mk("other", "Opaque", nil, nil), false},
		{mk(initialAdminSecretName, "Opaque", map[string]string{"cd.patrol.example/secret-type": "x"}, nil), false},
		{mk(internalTokenSecretName, "Opaque", nil, nil), false},
		{mk("sa", "kubernetes.io/service-account-token", map[string]string{"cd.patrol.example/secret-type": "x"}, nil), false},
		{mk("helm", "helm.sh/release.v1", nil, nil), false},
	}
	for _, c := range cases {
		assert.Equal(t, c.want, isPatrolSecret(c.obj, ref), c.obj.GetName())
		// Only managed Secrets are prune candidates: a referenced-only Secret is not.
		assert.Equal(t, c.want && c.obj.GetName() != "oidc", isManagedPatrolSecret(c.obj), c.obj.GetName())
	}
	assert.True(t, isRequiredSettingsSecret("patrol-secret"))
	assert.True(t, isRequiredSettingsSecret("patrol-notifications-secret"))
	assert.False(t, isRequiredSettingsSecret("repo"))

	refs := map[string]bool{}
	settingsSecretRefs(map[string]string{
		"oidc.config":     "name: SSO\nclientSecret: $oidc-secret:clientSecret\n",
		"dex.config":      "clientSecret: \"$dex-secret:secret\"\n",
		"webhook":         "$hook-secret:token",
		"resource.lua":    "local x = a$notref:value",
		"resource.jq":     ".spec | {($alsonot): 1}",
		"ignore.trailing": "price$5:00",
	}, refs)
	assert.Equal(t, map[string]bool{"oidc-secret": true, "dex-secret": true, "hook-secret": true}, refs)
}
