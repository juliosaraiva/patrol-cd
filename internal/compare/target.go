// errMessageAppPathDoesNotExist is the repo-server error text for a missing source path
// (internal/render.ErrMessageAppPathDoesNotExist; asserted equal in tests).
const errMessageAppPathDoesNotExist = "app path does not exist"

// maxTargetObjects bounds the number of desired objects of one Application.
const maxTargetObjects = 100000

var refKeyPattern = regexp.MustCompile(`^[a-zA-Z0-9_-]+$`)

// repoObjs is the desired state generated by the repo-server.
type repoObjs struct {
	targets        []*unstructured.Unstructured
	responses      []*apiclient.ManifestResponse
	mayHaveChanges bool
}

// renderEnv is what every manifest request of one comparison shares.
type renderEnv struct {
	st             *settings.Settings
	app            *v1alpha1.Application
	proj           *v1alpha1.AppProject
	instanceName   string
	hasMultiple    bool
	cc             cache.ClusterCache
	ccErr          error
	server         string
	noCache        bool
	noRevCache     bool
	evaluate       bool
	refSources     map[string]apiclient.RefTarget
	syncedRefs     map[string]apiclient.RefTarget
	kubeVersion    string
	apiVersions    []string
	sourceIntegrty *v1alpha1.SourceIntegrity
}

// getRepoObjs renders every source through the repo-server (upstream GetRepoObjs).
// revisions has one entry per source (empty entries use the source's targetRevision).
func (m *Manager) getRepoObjs(ctx context.Context, env *renderEnv, sources []v1alpha1.ApplicationSource, revisions []string) (*repoObjs, error) {
	st, app, proj := env.st, env.app, env.proj
	if env.ccErr != nil {
		return nil, fmt.Errorf("failed to get cluster version for cluster %q: %w", env.server, env.ccErr)
	}
	env.kubeVersion = env.cc.GetServerVersion()
	env.apiVersions = apiResourcesToStrings(env.cc.GetAPIResources())

	refs, err := m.refSources(ctx, sources, proj.Name, revisions)
	if err != nil {
		return nil, fmt.Errorf("failed to get ref sources: %w", err)
	}
	env.refSources = refs
	if env.hasMultiple {
		env.syncedRefs = syncedRefSources(refs, sources, app.Status.Sync.Revisions)
	}
	env.sourceIntegrty, _ = project.EffectiveSourceIntegrity(proj)

	var depRepos, ociRepos *dependencyRepos
	deps := func(includeOCI bool) (*dependencyRepos, error) {
		p := &depRepos
		if includeOCI {
			p = &ociRepos
		}
		if *p == nil {
			repos, creds, err := m.d.Repositories.ListDependencyRepositories(ctx, proj, includeOCI)
			if err != nil {
				return nil, fmt.Errorf("failed to list Helm repositories for project %q: %w", proj.Name, err)
			}
			*p = &dependencyRepos{repos: repos, creds: creds}
		}
		return *p, nil
	}

	enabled := map[string]bool{}
	for t, on := range st.EnabledSourceTypes() {
		enabled[string(t)] = on
	}
	kustomize := kustomizeOptions(st.Kustomize())
	helmOpts := apiclient.HelmOptions{ValuesFileSchemes: st.HelmValuesFileSchemes()}

	out := &repoObjs{}
	for i, source := range sources {
		revision := revisions[i]
		if revision == "" {
			revision = source.TargetRevision
		}
		repo, err := m.d.Repositories.GetRepository(ctx, source.RepoURL, proj.Name)
		if err != nil {
			return nil, fmt.Errorf("failed to get repo %q: %w", source.RepoURL, err)
		}
		if env.evaluate {
			resolved, changes, err := m.revisionChanges(ctx, env, source, i, revision, repo)
			if err != nil {
				return nil, fmt.Errorf("failed to evaluate revision changes for source %d of %d: %w", i+1, len(sources), err)
			}
			revision = resolved
			out.mayHaveChanges = out.mayHaveChanges || changes
		}

		d, err := deps(isOCI(source.RepoURL))
		if err != nil {
			return nil, err
		}
		req := &apiclient.ManifestRequest{
			Repo:                  *repo,
			Revision:              revision,
			NoCache:               env.noCache,
			NoRevisionCache:       env.noRevCache,
			AppName:               env.instanceName,
			AppNamespace:          app.Namespace,
			Namespace:             app.Spec.Destination.Namespace,
			Source:                source,
			Repos:                 d.repos,
			HelmRepoCreds:         d.creds,
			KustomizeOptions:      kustomize,
			HelmOptions:           helmOpts,
			KubeVersion:           env.kubeVersion,
			APIVersions:           env.apiVersions,
			InstanceLabelKey:      st.InstanceLabelKey(),
			TrackingMethod:        string(st.TrackingMethod()),
			InstallationID:        st.InstallationID(),
			EnabledSourceTypes:    enabled,
			HasMultipleSources:    env.hasMultiple,
			RefSources:            env.refSources,
			ProjectName:           proj.Name,
			ProjectSourceRepos:    proj.Spec.SourceRepos,
			ManifestGeneratePaths: app.Annotations[v1alpha1.AnnotationKeyManifestGeneratePaths],
			SourceIntegrity:       env.sourceIntegrty,
		}
		resp, err := m.d.RepoServer.GenerateManifest(ctx, req)
		if err != nil {
			genErr := fmt.Errorf("failed to generate manifest for source %d of %d: %w", i+1, len(sources), err)
			if h := app.Spec.SourceHydrator; h != nil && h.HydrateTo != nil && strings.Contains(err.Error(), errMessageAppPathDoesNotExist) {
				genErr = fmt.Errorf("%w - waiting for an external process to update %s from %s", genErr, h.SyncSource.TargetBranch, h.HydrateTo.TargetBranch)
			}
			return nil, genErr
		}
		if resp == nil {
			return nil, fmt.Errorf("failed to generate manifest for source %d of %d: empty response", i+1, len(sources))
		}
		objs, err := unmarshalManifests(resp.Manifests)
		if err != nil {
			return nil, fmt.Errorf("failed to unmarshal manifests for source %d of %d: %w", i+1, len(sources), err)
		}
		if len(out.targets)+len(objs) > maxTargetObjects {
			return nil, fmt.Errorf("source %d of %d: more than %d manifests", i+1, len(sources), maxTargetObjects)
		}
		out.targets = append(out.targets, objs...)
		resp = cloneIntegrity(resp)
		if len(sources) > 1 && resp.SourceIntegrityResult != nil {
			id := fmt.Sprintf("source %d of %d", i+1, len(sources))
			if source.Name != "" {
				id = "source " + source.Name
			}
			injectSourceName(resp.SourceIntegrityResult, id)
		}
		out.responses = append(out.responses, resp)
	}
	return out, nil
}

type dependencyRepos struct {
	repos []apiclient.Repository
	creds []apiclient.RepositoryCredentialTemplate
}

// revisionChanges reports whether a source may have changed since its synced revision
// without rendering it (upstream evaluateRevisionChanges).
func (m *Manager) revisionChanges(ctx context.Context, env *renderEnv, source v1alpha1.ApplicationSource, idx int, revision string, repo *apiclient.Repository) (string, bool, error) {
	app := env.app
	synced := app.Status.Sync.Revision
	if env.hasMultiple {
		synced = ""
		if idx < len(app.Status.Sync.Revisions) {
			synced = app.Status.Sync.Revisions[idx]
		}
	}
	if source.Ref != "" {
		// Ref sources are evaluated through the sources referencing them.
		return revision, false, nil
	}
	if synced == revision && revision != "" && len(env.refSources) == 0 {
		return revision, false, nil
	}
	annotation := app.Annotations[v1alpha1.AnnotationKeyManifestGeneratePaths]
	if synced == "" || repo.Depth != 0 || annotation == "" {
		return revision, true, nil
	}
	resp, err := m.d.RepoServer.UpdateRevisionForPaths(ctx, &apiclient.UpdateRevisionForPathsRequest{
		Repo:               *repo,
		AppLabelKey:        env.st.InstanceLabelKey(),
		AppName:            env.instanceName,
		Namespace:          app.Spec.Destination.Namespace,
		Source:             source,
		TrackingMethod:     string(env.st.TrackingMethod()),
		RefSources:         env.refSources,
		KubeVersion:        env.kubeVersion,
		APIVersions:        env.apiVersions,
		HasMultipleSources: env.hasMultiple,
		SyncedRevision:     synced,
		Revision:           revision,
		Paths:              sourceRefreshPaths(app, source),
		InstallationID:     env.st.InstallationID(),
		SyncedRefSources:   env.syncedRefs,
		NoRevisionCache:    env.noRevCache,
	})
	if err != nil {
		return "", false, fmt.Errorf("failed to update revision for paths: %w", err)
	}
	if resp == nil {
		return revision, true, nil
	}
	resolved := revision
	if resp.Revision != "" {
		resolved = resp.Revision
	}
	return resolved, resp.Changes, nil
}

// sourceRefreshPaths returns the manifest-generate-paths of a source (upstream
// GetSourceRefreshPaths): ';'-separated, trimmed, "/x" repository-relative, other entries
// relative to the source path; the hydrated sync source refreshes on its own path.
func sourceRefreshPaths(app *v1alpha1.Application, source v1alpha1.ApplicationSource) []string {
	if h := app.Spec.SourceHydrator; h != nil {
		sync := h.GetSyncSource()
		if sync.RepoURL == source.RepoURL && sync.Path == source.Path && sync.TargetRevision == source.TargetRevision {
			return []string{source.Path}
		}
	}
	annotation := app.Annotations[v1alpha1.AnnotationKeyManifestGeneratePaths]
	var paths []string
	for item := range strings.SplitSeq(annotation, ";") {
		item = strings.TrimSpace(item)
		if item == "" {
			continue
		}
		if strings.HasPrefix(item, "/") {
			paths = append(paths, item[1:])
			continue
		}
		paths = append(paths, filepath.Clean(filepath.Join(source.Path, item)))
	}
	return paths
}

// refSources maps "$<ref>" to the referenced source of a multi-source Application (upstream
// GetRefSources): ref names are validated and unique; revisions override targetRevision.
func (m *Manager) refSources(ctx context.Context, sources []v1alpha1.ApplicationSource, projectName string, revisions []string) (map[string]apiclient.RefTarget, error) {
	seen := map[string]bool{}
	for _, s := range sources {
		if s.Ref == "" {
			continue
		}
		if !refKeyPattern.MatchString(s.Ref) {
			return nil, fmt.Errorf("sources.ref %s cannot contain any special characters except '_' and '-'", s.Ref)
		}
		key := "$" + s.Ref
		if seen[key] {
			return nil, errors.New("invalid sources: multiple sources had the same `ref` key")
		}
		seen[key] = true
	}
	out := map[string]apiclient.RefTarget{}
	for i, s := range sources {
		if s.Ref == "" {
			continue
		}
		repo, err := m.d.Repositories.GetRepository(ctx, s.RepoURL, projectName)
		if err != nil {
			return nil, fmt.Errorf("failed to get repository %s: %w", s.RepoURL, err)
		}
		rev := s.TargetRevision
		if i < len(revisions) && revisions[i] != "" {
			rev = revisions[i]
		}
		out["$"+s.Ref] = apiclient.RefTarget{Repo: *repo, TargetRevision: rev, Chart: s.Chart}
	}
	return out, nil
}

// syncedRefSources returns the ref sources at the synced revisions (upstream
// GetSyncedRefSources).
func syncedRefSources(refs map[string]apiclient.RefTarget, sources []v1alpha1.ApplicationSource, syncRevisions []string) map[string]apiclient.RefTarget {
	out := map[string]apiclient.RefTarget{}
	for i, s := range sources {
		if s.Ref == "" {
			continue
		}
		key := "$" + s.Ref
		rev := ""
		if i < len(syncRevisions) {
			rev = syncRevisions[i]
		}
		ref := refs[key]
		out[key] = apiclient.RefTarget{Repo: ref.Repo, TargetRevision: rev, Chart: ref.Chart}
	}
	return out
}

func isOCI(repoURL string) bool {
	return len(repoURL) >= 6 && strings.EqualFold(repoURL[:6], "oci://")
}

func kustomizeOptions(k settings.Kustomize) apiclient.KustomizeOptions {
	out := apiclient.KustomizeOptions{BuildOptions: k.BuildOptions}
	for _, v := range k.Versions {
		if out.Versions == nil {
			out.Versions = map[string]string{}
			out.VersionBuildOptions = map[string]string{}
		}
		out.Versions[v.Name] = v.Path
		if v.BuildOptions != "" {
			out.VersionBuildOptions[v.Name] = v.BuildOptions
		}
	}
	return out
}

// apiResourcesToStrings lists "group/version" and "group/version/Kind" of every served
// resource, sorted (upstream APIResourcesToStrings with kinds).
func apiResourcesToStrings(resources []cache.APIResourceInfo) []string {
	set := map[string]bool{}
	for _, r := range resources {
		gv := r.GroupVersionResource.GroupVersion().String()
		set[gv] = true
		set[gv+"/"+r.GroupKind.Kind] = true
	}
	return slices.Sorted(maps.Keys(set))
}

// unmarshalManifests decodes JSON (or YAML) documents; "" and "null" yield nil entries.
func unmarshalManifests(manifests []string) ([]*unstructured.Unstructured, error) {
	out := make([]*unstructured.Unstructured, 0, len(manifests))
	for _, m := range manifests {
		obj, err := unmarshalManifest(m)
		if err != nil {
			return nil, err
		}
		out = append(out, obj)
	}
	return out, nil
}

func unmarshalManifest(manifest string) (*unstructured.Unstructured, error) {
	trimmed := strings.TrimSpace(manifest)
	if trimmed == "" || trimmed == "null" {
		return nil, nil
	}
	data := []byte(trimmed)
	if trimmed[0] != '{' {
		j, err := yaml.YAMLToJSON(data)
		if err != nil {
			return nil, fmt.Errorf("failed to decode manifest: %w", err)
		}
		if string(j) == "null" {
			return nil, nil
		}
		data = j
	}
	obj := &unstructured.Unstructured{}
	if err := obj.UnmarshalJSON(data); err != nil {
		return nil, err
	}
	return obj, nil
}

func cloneIntegrity(resp *apiclient.ManifestResponse) *apiclient.ManifestResponse {
	cp := *resp
	if resp.SourceIntegrityResult != nil {
		r := &apiclient.SourceIntegrityResult{}
		for _, c := range resp.SourceIntegrityResult.Checks {
			r.Checks = append(r.Checks, apiclient.SourceIntegrityCheck{Name: c.Name, Problems: slices.Clone(c.Problems)})
		}
		cp.SourceIntegrityResult = r
	}
	return &cp
}

func injectSourceName(r *apiclient.SourceIntegrityResult, id string) {
	for ci := range r.Checks {
		for pi, p := range r.Checks[ci].Problems {
			r.Checks[ci].Problems[pi] = id + ": " + p
		}
	}
}

// integrityError formats failed source integrity checks (upstream AsError: one
// "<check>: <problem>" line per problem).
func integrityError(r *apiclient.SourceIntegrityResult) string {
	if r == nil {
		return ""
	}
	var lines []string
	for _, c := range r.Checks {
		for _, p := range c.Problems {
			lines = append(lines, c.Name+": "+p)
		}
	}
	return strings.Join(lines, "\n")
}

// scopeFunc reports whether a group/kind is namespaced; an error means the scope is unknown.
type scopeFunc func(gk schema.GroupKind) (bool, error)

// normalizeTargets sets namespaces (cleared for cluster-scoped kinds, defaulted for
// namespaced or unknown ones; tracking is re-applied to changed objects), keys objects by
// group/kind/namespace/name (generateName-only objects get name generateName+index) and keeps
// the last of repeated keys with a RepeatedResourceWarning (upstream NormalizeTargetObjects).
// The result keeps first-appearance order of keys.
func normalizeTargets(namespace string, objs []*unstructured.Unstructured, isNamespaced scopeFunc, setAppInstance func(*unstructured.Unstructured) error) ([]*unstructured.Unstructured, []Condition, error) {
	byKey := map[ResourceKey][]*unstructured.Unstructured{}
	var order []ResourceKey
	for i, obj := range objs {
		if obj == nil {
			continue
		}
		namespaced, err := isNamespaced(obj.GroupVersionKind().GroupKind())
		namespacedOrUnknown := err != nil || namespaced
		modified := false
		switch {
		case !namespacedOrUnknown && obj.GetNamespace() != "":
			obj.SetNamespace("")
			modified = true
		case namespacedOrUnknown && obj.GetNamespace() == "":
			obj.SetNamespace(namespace)
			modified = true
		}
		if modified {
			if err := setAppInstance(obj); err != nil {
				return nil, nil, fmt.Errorf("failed to set app instance label on resource %s/%s: %w", obj.GetKind(), obj.GetName(), err)
			}
		}
		key := cache.KeyOf(obj)
		if key.Name == "" && obj.GetGenerateName() != "" {
			key.Name = fmt.Sprintf("%s%d", obj.GetGenerateName(), i)
		}
		if _, ok := byKey[key]; !ok {
			order = append(order, key)
		}
		byKey[key] = append(byKey[key], obj)
	}
	var conds []Condition
	out := make([]*unstructured.Unstructured, 0, len(order))
	for _, key := range order {
		list := byKey[key]
		if len(list) > 1 {
			conds = append(conds, newCondition(v1alpha1.ApplicationConditionRepeatedResourceWarning, v1alpha1.ReasonRepeatedResource,
				fmt.Sprintf("Resource %s appeared %d times among application resources.", key.String(), len(list))))
		}
		out = append(out, list[len(list)-1])
	}
	return out, conds, nil
}
