package main

import (
	"bytes"
	"fmt"
	"slices"
	"strings"

	"github.com/juliosaraiva/patrol-cd/internal/settings"
)

// projectedComponents are the components that read patrol-cmd-params-cm only through
// environment variables (no Kubernetes access), so the install projects every key into them.
var projectedComponents = []settings.Component{settings.ComponentCommitServer, settings.ComponentRepoServer}

// profileComponents maps settings components to the chart's component names for the
// profiler toggle file (<prefix>.profile.enabled projected as /home/patrol/params/profiler.enabled).
var chartComponentName = map[settings.Component]string{
	settings.ComponentServer:                  "server",
	settings.ComponentController:              "controller",
	settings.ComponentRepoServer:              "repo-server",
	settings.ComponentAppSetController:        "applicationset-controller",
	settings.ComponentNotificationsController: "notifications-controller",
	settings.ComponentCommitServer:            "commit-server",
}

// secretParams are never projected from patrol-cmd-params-cm: the chart refuses them in
// configs.params and passes them from a Secret instead (tracing.headersSecret).
var secretParams = map[string]bool{"otlp.headers": true}

// usable reports whether a parameter has an effect in Patrol CD (not NotApplicable, not
// deprecated): only those are projected and accepted by the chart.
func usable(s settings.ParamSpec) bool {
	return s.NotApplicable == "" && s.Deprecated == ""
}

// renderParamsTemplate renders templates/_generated_params.tpl.
func renderParamsTemplate() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("{{/* Code generated by `go run ./hack/helmdocs` from internal/settings (ParamSpecs). DO NOT EDIT. */}}\n")
	b.WriteString("{{/*\n")
	b.WriteString("env: patrol-cmd-params-cm keys and the environment variables they are projected into, for the\n")
	b.WriteString("components without Kubernetes access. profile: the profiler toggle key of each component.\n")
	b.WriteString("*/}}\n")
	b.WriteString("{{- define \"patrol.generated.params\" -}}\n")
	b.WriteString("env:\n")
	for _, c := range projectedComponents {
		name, ok := chartComponentName[c]
		if !ok {
			return nil, fmt.Errorf("no chart name for component %s", c)
		}
		specs := settings.ParamsForComponent(c)
		slices.SortFunc(specs, func(a, b settings.ParamSpec) int { return strings.Compare(a.Key, b.Key) })
		fmt.Fprintf(&b, "  %s:\n", name)
		n := 0
		for _, s := range specs {
			if !usable(s) || s.Env == "" || secretParams[s.Key] {
				continue
			}
			fmt.Fprintf(&b, "    - key: %s\n      env: %s\n", s.Key, s.Env)
			n++
		}
		if n == 0 {
			return nil, fmt.Errorf("component %s has no projected parameter", c)
		}
	}
	b.WriteString("profile:\n")
	var profiles []string
	for _, s := range settings.ParamSpecs() {
		if !strings.HasSuffix(s.Key, ".profile.enabled") || s.Env != "" || !usable(s) {
			continue
		}
		name, ok := chartComponentName[s.Component]
		if !ok {
			return nil, fmt.Errorf("no chart name for component %s (%s)", s.Component, s.Key)
		}
		profiles = append(profiles, fmt.Sprintf("  %s: %s\n", name, s.Key))
	}
	slices.Sort(profiles)
	profiles = slices.Compact(profiles)
	if len(profiles) == 0 {
		return nil, fmt.Errorf("no profiler toggle keys found")
	}
	for _, p := range profiles {
		b.WriteString(p)
	}
	b.WriteString("{{- end -}}\n")
	return b.Bytes(), nil
}

// acceptedParamKeys returns the patrol-cmd-params-cm keys the chart accepts in configs.params:
// every usable key, sorted and deduplicated.
func acceptedParamKeys() []string {
	var keys []string
	for _, s := range settings.ParamSpecs() {
		if usable(s) {
			keys = append(keys, s.Key)
		}
	}
	slices.Sort(keys)
	return slices.Compact(keys)
}
