package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// The CRDs are shipped as templates (not Helm's crds/ directory, which Helm never upgrades):
// templates/crds/<file> is deploy/crds/<file> with a guard (crds.install, or crds.admissionPolicy
// for the ValidatingAdmissionPolicy), the keep annotation and the chart labels inserted. The
// body is copied byte for byte otherwise, so `-check` proves the chart cannot drift from the
// generated CRDs.

const crdHeader = "{{- /* Code generated by `go run ./hack/helmdocs` from deploy/crds/%s. DO NOT EDIT. */ -}}\n"

const crdAnnotations = `    {{- if .Values.crds.keep }}
    helm.sh/resource-policy: keep
    {{- end }}
    {{- with .Values.crds.annotations }}
    {{- toYaml . | nindent 4 }}
    {{- end }}
`

const crdExtraLabels = `    {{- include "patrol.crdLabels" . | nindent 4 }}
`

var topLevelName = regexp.MustCompile(`^  name: \S+$`)

// renderCRDTemplates returns templates/crds/<file> for every YAML file of crdDir.
func renderCRDTemplates(crdDir string) (map[string][]byte, error) {
	files, err := filepath.Glob(filepath.Join(crdDir, "*.yaml"))
	if err != nil {
		return nil, err
	}
	slices.Sort(files)
	if len(files) == 0 {
		return nil, fmt.Errorf("no CRD files in %s", crdDir)
	}
	out := map[string][]byte{}
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		base := filepath.Base(f)
		if bytes.Contains(data, []byte("{{")) || bytes.Contains(data, []byte("}}")) {
			return nil, fmt.Errorf("%s contains template delimiters; it cannot be embedded in a template", f)
		}
		var body string
		switch {
		case strings.HasPrefix(base, "cd.patrol.example_"):
			body, err = templateCRD(string(data))
		case base == "operations-admission-policy.yaml":
			body, err = templateAdmissionPolicy(string(data))
		default:
			err = fmt.Errorf("unexpected file (not a CRD or the Operation admission policy)")
		}
		if err != nil {
			return nil, fmt.Errorf("%s: %w", f, err)
		}
		out[base] = []byte(fmt.Sprintf(crdHeader, base) + body)
	}
	return out, nil
}

// templateCRD inserts the keep annotation and the labels into a controller-gen CRD:
//
//	---
//	apiVersion: apiextensions.k8s.io/v1
//	kind: CustomResourceDefinition
//	metadata:
//	  annotations:
//	    controller-gen.kubebuilder.io/version: ...
//	  name: <plural>.cd.patrol.example
//	spec:
func templateCRD(src string) (string, error) {
	lines := strings.SplitAfter(src, "\n")
	want := []string{"---\n", "apiVersion: apiextensions.k8s.io/v1\n", "kind: CustomResourceDefinition\n", "metadata:\n", "  annotations:\n"}
	if len(lines) < len(want)+3 {
		return "", fmt.Errorf("too short for a CRD")
	}
	for i, w := range want {
		if lines[i] != w {
			return "", fmt.Errorf("line %d is %q, want %q (controller-gen layout changed; update hack/helmdocs)", i+1, strings.TrimSpace(lines[i]), strings.TrimSpace(w))
		}
	}
	i := len(want)
	for i < len(lines) && strings.HasPrefix(lines[i], "    ") {
		i++
	}
	if i >= len(lines) || !topLevelName.MatchString(strings.TrimRight(lines[i], "\n")) || i+1 >= len(lines) || lines[i+1] != "spec:\n" {
		return "", fmt.Errorf("expected \"  name:\" followed by \"spec:\" after the annotations")
	}
	var b strings.Builder
	b.WriteString("{{- if .Values.crds.install }}\n")
	for _, l := range lines[:i] {
		b.WriteString(l)
	}
	b.WriteString(crdAnnotations)
	b.WriteString("  labels:\n    app.kubernetes.io/part-of: patrol-cd\n")
	b.WriteString(crdExtraLabels)
	for _, l := range lines[i:] {
		b.WriteString(l)
	}
	if !strings.HasSuffix(src, "\n") {
		b.WriteString("\n")
	}
	b.WriteString("{{- end }}\n")
	return b.String(), nil
}

// templateAdmissionPolicy inserts the annotations and labels into each object of the
// hand-written ValidatingAdmissionPolicy file, whose objects start with
//
//	metadata:
//	  name: operations.cd.patrol.example
//	  labels:
//	    app.kubernetes.io/part-of: patrol-cd
func templateAdmissionPolicy(src string) (string, error) {
	lines := strings.SplitAfter(src, "\n")
	var b strings.Builder
	b.WriteString("{{- if .Values.crds.admissionPolicy }}\n")
	objects := 0
	for i := 0; i < len(lines); i++ {
		l := lines[i]
		if l != "metadata:\n" {
			b.WriteString(l)
			continue
		}
		if i+3 >= len(lines) || !topLevelName.MatchString(strings.TrimRight(lines[i+1], "\n")) ||
			lines[i+2] != "  labels:\n" || lines[i+3] != "    app.kubernetes.io/part-of: patrol-cd\n" {
			return "", fmt.Errorf("object metadata at line %d does not have the expected name/labels layout", i+1)
		}
		b.WriteString(l)
		b.WriteString(policyAnnotations)
		b.WriteString(lines[i+1] + lines[i+2] + lines[i+3])
		b.WriteString(crdExtraLabels)
		i += 3
		objects++
	}
	if objects != 2 {
		return "", fmt.Errorf("found %d objects, want 2 (policy and binding)", objects)
	}
	if !strings.HasSuffix(src, "\n") {
		b.WriteString("\n")
	}
	b.WriteString("{{- end }}\n")
	return b.String(), nil
}

// policyAnnotations renders the annotations block of the policy objects only when there is an
// annotation to set (the source objects have none).
const policyAnnotations = `  {{- if or .Values.crds.keep .Values.crds.annotations }}
  annotations:
` + crdAnnotations + `  {{- end }}
`
