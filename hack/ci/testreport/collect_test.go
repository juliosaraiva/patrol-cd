// real-probe.json is a real go 1.27.3 capture of testdata/real-probe/a_test.go (see README.md):
// skips in every shape the reason tracker and the grouping have to handle.
func TestRealProbe(t *testing.T) {
	t.Parallel()
	const pkg = "example.com/probe/a"
	s := collectFile(t, "testdata/real-probe.json", "testdata/real-probe-skips.txt", "testdata/real-probe-must-run.txt", false, false)

	if s.Totals.Tests != 28 || s.Totals.TestsSkipped != 20 || s.Totals.SkipsAllowed != 16 || s.Totals.SkipsForbidden != 4 || s.Totals.TestsFailed != 1 || s.Totals.PackagesNoTestFiles != 1 {
		t.Fatalf("totals %+v", s.Totals)
	}
	if s.Result != resultFailed || s.TestsResult != resultFailed || s.PolicyResult != resultViolations || len(s.StaleAllowlist) != 0 {
		t.Fatalf("result %q %q %q, stale %+v", s.Result, s.TestsResult, s.PolicyResult, s.StaleAllowlist)
	}

	type reason struct {
		text      string
		location  string
		allowed   bool
		truncated bool
	}
	tests := []struct {
		test     string
		subtests int
		allowed  bool
		reasons  []reason
		hint     string // prefix of the first reason's hint
	}{
		// A parent that calls t.Skip after a passing subtest is a skip of its own.
		{test: "TestParentSkipAfterPass", reasons: []reason{{"forbidden parent reason", "a_test.go:19", false, false}}},
		// Every member of a group is matched: one allowed reason does not hide two forbidden ones.
		{test: "TestMixedGroup", subtests: 3, reasons: []reason{
			{"allowed reason", "a_test.go:24", true, false}, {"forbidden y", "a_test.go:25", false, false}, {"forbidden z", "a_test.go:26", false, false},
		}},
		// Three levels: the subtests' parents are found by the longest prefix.
		{test: "TestNested3", subtests: 2, allowed: true, reasons: []reason{{"allowed reason", "a_test.go:32", true, false}, {"allowed reason", "a_test.go:35", true, false}}},
		{test: "TestParallel", subtests: 3, allowed: true, reasons: []reason{{"allowed reason", "a_test.go:111", true, false}}},
		// A zero-indent "noise.go:1:" line printed by a cleanup is not a message.
		{test: "TestStdoutAfterSkip", allowed: true, reasons: []reason{{"allowed reason", "a_test.go:42", true, false}}},
		// A t.Log in a cleanup is printed after the t.Skip message and becomes the reason; the
		// skip fails, and the hint points at the message before it.
		{test: "TestCleanupLogAfterSkip", reasons: []reason{{"cleanup log line", "a_test.go:48", false, false}}, hint: `the earlier message "allowed reason" at a_test.go:49 matches allowlist line 3; if it is the t.Skip message, `},
		{test: "TestGuardedCleanupLog", allowed: true, reasons: []reason{{"allowed reason", "a_test.go:59", true, false}}},
		// Output without a newline, then the message on the same line.
		{test: "TestStdoutNoNewline", allowed: true, reasons: []reason{{"allowed reason", "a_test.go:65", true, false}}},
		{test: "TestStdoutNoNewlineSkipNow", allowed: true, reasons: []reason{{"", "", true, false}}},
		{test: "TestHeaderLikeContinuation", allowed: true, reasons: []reason{{"allowed reason\n    gen.go:12: generated by stringer", "a_test.go:76", true, false}}},
		// 3005 bytes in three 1024-byte events and a last one: joined, and matched whole.
		{test: "TestLongSkip", allowed: true, reasons: []reason{{"long " + strings.Repeat("a", 3000), "a_test.go:81", true, false}}},
		{test: "TestHugeSkip", allowed: true, reasons: []reason{{"huge " + strings.Repeat("b", maxReasonBytes-len("huge ")), "a_test.go:86", true, true}}},
		{test: "TestSkipNow", allowed: true, reasons: []reason{{"", "", true, false}}},
		{test: "TestLogThenSkipNow", allowed: true, reasons: []reason{{"logged before SkipNow", "a_test.go:101", true, false}}},
	}
	for _, tt := range tests {
		sk := findSkip(s, pkg, tt.test)
		if sk == nil {
			t.Errorf("%s: no skip entry", tt.test)
			continue
		}
		var got []reason
		for _, r := range sk.Reasons {
			got = append(got, reason{r.Text, r.Location, r.Allowed, r.Truncated})
		}
		if sk.Subtests != tt.subtests || sk.Allowed != tt.allowed || !slices.Equal(got, tt.reasons) {
			t.Errorf("%s: got subtests %d, allowed %v, reasons %+v; want %d, %v, %+v", tt.test, sk.Subtests, sk.Allowed, got, tt.subtests, tt.allowed, tt.reasons)
		}
		if h := sk.Reasons[0].Hint; (tt.hint == "") != (h == "") || !strings.HasPrefix(h, tt.hint) {
			t.Errorf("%s: hint %q, want a hint starting %q", tt.test, h, tt.hint)
		}
	}
	if sk := findSkip(s, pkg, "TestManyLineSkip"); sk == nil || !sk.Reasons[0].Truncated || strings.Count(sk.Reasons[0].Text, "\n") != maxReasonLines-1 || !sk.Allowed {
		t.Errorf("TestManyLineSkip: %+v", sk)
	}
	if len(s.Skips) != 15 {
		t.Errorf("got %d skip entries, want 15", len(s.Skips))
	}

	var violations []string
	for _, v := range s.MustRunViolations {
		for _, ts := range v.Tests {
			violations = append(violations, ts.Test+":"+ts.Status)
		}
	}
	if !slices.Equal(violations, []string{"TestFail:fail", "TestNested3:subtests-skipped"}) {
		t.Errorf("must-run violations %q", violations)
	}
	if len(s.Failures) != 1 || s.Failures[0].Test != "TestFail" || !slices.Equal(s.Failures[0].Output, []string{"    a_test.go:12: before the failure", "    a_test.go:13: got 1, want 2"}) {
		t.Errorf("failures %+v", s.Failures)
	}
}

// The probe stream cut in the middle of a line that test2json split into several events, as
// when a job is killed: the parts that arrived are joined, and what ran before is reported.
func TestTruncatedRealProbe(t *testing.T) {
	t.Parallel()
	in, err := os.ReadFile("testdata/real-probe.json")
	if err != nil {
		t.Fatal(err)
	}
	marker := []byte(`"Test":"TestHugeSkip","Output":"bbbb`)
	cut := 0
	for i := 0; i < 3; i++ { // cut inside the fourth 1024-byte event of the split skip line
		j := bytes.Index(in[cut:], marker)
		if j < 0 {
			t.Fatal("marker not found")
		}
		cut += j + len(marker)
	}
	allow, err := loadAllowlist("testdata/real-probe-skips.txt")
	if err != nil {
		t.Fatal(err)
	}
	c := newCollector(allow, nil, false)
	if err := c.read(bytes.NewReader(in[:cut])); err != nil {
		t.Fatal(err)
	}
	s := c.summary("t", false)
	if s.TestsResult != resultFailed || s.Totals.PackagesIncomplete != 1 || s.Totals.TestsIncomplete != 1 || s.Totals.NonJSONLines != 1 {
		t.Fatalf("result %q, totals %+v", s.TestsResult, s.Totals)
	}
	if got := resultLine(s); got != "FAILED: 1 package did not finish, 1 failed test, 1 test did not finish; 4 forbidden skipped tests" {
		t.Fatalf("headline %q", got)
	}
	var hang *Failure
	for i := range s.Failures {
		if s.Failures[i].Test == "TestHugeSkip" {
			hang = &s.Failures[i]
		}
	}
	// Three complete 1024-byte events arrived: one line of 3072 bytes, clipped for the report.
	if hang == nil || hang.Kind != failIncomplete || len(hang.Output) != 1 ||
		hang.Output[0] != "    a_test.go:86: huge "+strings.Repeat("b", maxLineBytes-len("    a_test.go:86: huge "))+fmt.Sprintf(" ... (%d more bytes)", 3*1024-maxLineBytes) {
		t.Fatalf("TestHugeSkip failure %+v", hang)
	}
	if sk := findSkip(s, "example.com/probe/a", "TestLongSkip"); sk == nil || !sk.Allowed {
		t.Fatalf("TestLongSkip, before the cut: %+v", sk)
	}
}

