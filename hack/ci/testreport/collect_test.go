// collectFile runs the collector over a testdata file with rules from testdata files ("" for
// none).
func collectFile(t *testing.T, input, skips, mustRun string, requirePkgs, strict bool) *Summary {
	t.Helper()
	allow, err := loadAllowlist(skips)
	if err != nil {
		t.Fatal(err)
	}
	must, err := loadMustRun(mustRun)
	if err != nil {
		t.Fatal(err)
	}
	f, err := os.Open(input)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close() //nolint:errcheck // read-only file
	c := newCollector(allow, must, requirePkgs)
	if err := c.read(f); err != nil {
		t.Fatal(err)
	}
	return c.summary("t", strict)
}

func findSkip(s *Summary, pkg, test string) *Skip {
	for i := range s.Skips {
		if s.Skips[i].Package == pkg && s.Skips[i].Test == test {
			return &s.Skips[i]
		}
	}
	return nil
}

