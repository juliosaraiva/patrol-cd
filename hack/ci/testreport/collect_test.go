// The hint names an earlier message that the allowlist matches, only for a reason it does not.
func TestHint(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		logs []string // output lines of TestA before its SKIP line
		hint string
	}{
		{name: "allowed reason after an allowed log", logs: []string{"    a_test.go:1: allowed reason", "    a_test.go:2: allowed reason"}},
		{name: "forbidden reason, no earlier message", logs: []string{"    a_test.go:2: tool missing"}},
		{name: "forbidden reason, no earlier message matches", logs: []string{"    a_test.go:1: starting", "    a_test.go:2: tool missing"}},
		{
			name: "a cleanup log after an allowed skip", logs: []string{"    a_test.go:2: allowed reason", "    a_test.go:1: server stopped"},
			hint: `the earlier message "allowed reason" at a_test.go:2 matches allowlist line 1; if it is the t.Skip message, a log written after t.Skip (by a t.Cleanup or a goroutine) took its place: guard that log with if !t.Skipped()`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			var b strings.Builder
			b.WriteString(`{"Action":"run","Package":"p","Test":"TestA"}` + "\n")
			for _, l := range tt.logs {
				fmt.Fprintf(&b, `{"Action":"output","Package":"p","Test":"TestA","Output":%q}`+"\n", l+"\n")
			}
			b.WriteString(`{"Action":"skip","Package":"p","Test":"TestA","Elapsed":0}` + "\n" + `{"Action":"pass","Package":"p","Elapsed":0}` + "\n")
			rules, err := parseAllowlist("f", strings.NewReader("p\tTest.*\tallowed reason\twhy\n")) // per subtest: matching counts hits
			if err != nil {
				t.Fatal(err)
			}
			c := newCollector(&allowlist{rules: rules}, nil, false)
			if err := c.read(strings.NewReader(b.String())); err != nil {
				t.Fatal(err)
			}
			s := c.summary("t", false)
			if len(s.Skips) != 1 || s.Skips[0].Reasons[0].Hint != tt.hint {
				t.Fatalf("skips %+v", s.Skips)
			}
		})
	}
}

