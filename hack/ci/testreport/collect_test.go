func TestCapture(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name        string
		lines       int
		errAt       []int // indexes of lines marked as t.Error output
		wantKept    int
		wantOmitted int
		mustHave    []string
	}{
		{name: "short output is kept whole", lines: 5, wantKept: 5},
		{name: "exactly the cap", lines: captureHead + captureTail, wantKept: captureHead + captureTail},
		{name: "long output keeps head and tail", lines: 1000, wantKept: captureHead + captureTail, wantOmitted: 1000 - captureHead - captureTail, mustHave: []string{"line 0", "line 9", "line 980", "line 999"}},
		{name: "error lines in the middle are kept", lines: 1000, errAt: []int{500, 501}, wantKept: captureHead + captureTail + 2, wantOmitted: 1000 - captureHead - captureTail - 2, mustHave: []string{"line 500", "line 501"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			var c capture
			for i := 0; i < tt.lines; i++ {
				c.add(fmt.Sprintf("line %d", i), slices.Contains(tt.errAt, i), 0)
			}
			out, omitted := c.lines()
			kept := 0
			for _, l := range out {
				if strings.HasPrefix(l, "line ") {
					kept++
				}
			}
			if kept != tt.wantKept || omitted != tt.wantOmitted {
				t.Fatalf("kept %d lines, omitted %d; want %d and %d\n%s", kept, omitted, tt.wantKept, tt.wantOmitted, strings.Join(out, "\n"))
			}
			if kept > captureHead+captureErrors+captureTail {
				t.Fatalf("kept %d lines, more than the cap", kept)
			}
			for _, m := range tt.mustHave {
				if !slices.Contains(out, m) {
					t.Errorf("%q missing from %q", m, out)
				}
			}
		})
	}
}

func TestClip(t *testing.T) {
	t.Parallel()
	long := strings.Repeat("é", maxLineBytes) // 2 bytes per rune
	got := clip(long)
	if !strings.HasSuffix(got, fmt.Sprintf("... (%d more bytes)", len(long)-maxLineBytes)) {
		t.Fatalf("clip suffix: %q", got[len(got)-40:])
	}
	if !strings.HasPrefix(got, strings.Repeat("é", maxLineBytes/2)+" ") {
		t.Fatal("clip did not cut on a rune boundary")
	}
	if clip("short\r") != "short" {
		t.Fatal("clip keeps a trailing carriage return")
	}
	if got := clip("x\r::error::y\r"); got != `x\r::error::y` {
		t.Fatalf("clip of a line with a carriage return: %q", got)
	}
	if got := clipN("short", 7); got != "short ... (7 more bytes)" {
		t.Fatalf("clipN of a short line with dropped bytes: %q", got)
	}
	if got := clipN(long, 7); !strings.HasSuffix(got, fmt.Sprintf("... (%d more bytes)", len(long)-maxLineBytes+7)) {
		t.Fatalf("clipN suffix: %q", got[len(got)-40:])
	}
	tests := []struct {
		text      string
		truncated bool
		want      string
	}{
		{"why", false, "why"},
		{"why", true, "why ... (truncated)"},
		{strings.Repeat("é", maxLineBytes), false, strings.Repeat("é", maxLineBytes/2) + " ... (truncated)"},
	}
	for _, tt := range tests {
		if got := shortReason(tt.text, tt.truncated); got != tt.want {
			t.Errorf("shortReason(%.20q, %v) = %.40q, want %.40q", tt.text, tt.truncated, got, tt.want)
		}
	}
	if cutRunes("aé", 2) != "a" || cutRunes("ab", 5) != "ab" || cutRunes("éa", 0) != "" {
		t.Fatal("cutRunes")
	}
}

// find reports the allowing lines without counting hits; match counts them for the stale check.
func TestAllowlistHits(t *testing.T) {
	t.Parallel()
	rules, err := parseAllowlist("f", strings.NewReader("p\tTestA\t.*\tone\np\tTestB\t.*\ttwo\n"))
	if err != nil {
		t.Fatal(err)
	}
	a := &allowlist{rules: rules}
	if got := a.find("p", "TestA", "x"); !slices.Equal(got, []int{1}) || rules[0].hits != 0 {
		t.Fatalf("find = %v, hits %d", got, rules[0].hits)
	}
	if got := a.match("p", "TestA", "x"); !slices.Equal(got, []int{1}) || rules[0].hits != 1 || rules[1].hits != 0 {
		t.Fatalf("match = %v, hits %d %d", got, rules[0].hits, rules[1].hits)
	}
}

