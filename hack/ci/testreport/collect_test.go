// A full CI run has well over 100,000 events. The stream is generated on the fly and read
// through a pipe, and only failing and skipping tests keep output. The size is kept at 40,300
// events so that the test stays quick under -race on a 2 vCPU runner.
func TestLargeStream(t *testing.T) {
	t.Parallel()
	const pkgs, tests = 100, 100 // 100*100*4 + 100*3 events
	pr, pw := io.Pipe()
	go func() {
		defer pw.Close() //nolint:errcheck // in-memory pipe
		for p := 0; p < pkgs; p++ {
			var b strings.Builder
			pkg := fmt.Sprintf("example.com/big/p%03d", p)
			fmt.Fprintf(&b, `{"Action":"start","Package":%q}`+"\n", pkg)
			for i := 0; i < tests; i++ {
				name := fmt.Sprintf("Test%03d", i)
				fmt.Fprintf(&b, `{"Action":"run","Package":%q,"Test":%q}`+"\n", pkg, name)
				fmt.Fprintf(&b, `{"Action":"output","Package":%q,"Test":%q,"Output":"=== RUN   %s\n","OutputType":"frame"}`+"\n", pkg, name, name)
				if i == 7 {
					fmt.Fprintf(&b, `{"Action":"output","Package":%q,"Test":%q,"Output":"    x_test.go:1: tool missing\n"}`+"\n", pkg, name)
					fmt.Fprintf(&b, `{"Action":"skip","Package":%q,"Test":%q,"Elapsed":0}`+"\n", pkg, name)
				} else {
					fmt.Fprintf(&b, `{"Action":"output","Package":%q,"Test":%q,"Output":"    x_test.go:1: %s\n"}`+"\n", pkg, name, strings.Repeat("x", 200))
					fmt.Fprintf(&b, `{"Action":"pass","Package":%q,"Test":%q,"Elapsed":0.01}`+"\n", pkg, name)
				}
			}
			fmt.Fprintf(&b, `{"Action":"output","Package":%q,"Output":"ok\n"}`+"\n", pkg)
			fmt.Fprintf(&b, `{"Action":"pass","Package":%q,"Elapsed":1}`+"\n", pkg)
			if _, err := io.WriteString(pw, b.String()); err != nil {
				return
			}
		}
	}()
	rules, err := parseAllowlist("a", strings.NewReader("example\\.com/big/p00[0-9]\tTest007\ttool missing\tdemo\n"))
	if err != nil {
		t.Fatal(err)
	}
	c := newCollector(&allowlist{rules: rules}, nil, false)
	if err := c.read(pr); err != nil {
		t.Fatal(err)
	}
	s := c.summary("t", false)
	if s.Totals.Events != pkgs*tests*4+pkgs*3 || s.Totals.Tests != pkgs*tests || s.Totals.TestsSkipped != pkgs {
		t.Fatalf("totals %+v", s.Totals)
	}
	if s.Totals.SkipsAllowed != 10 || s.Totals.SkipsForbidden != pkgs-10 || len(s.Skips) != pkgs {
		t.Fatalf("skips: allowed %d forbidden %d entries %d", s.Totals.SkipsAllowed, s.Totals.SkipsForbidden, len(s.Skips))
	}
	if len(s.SlowestPackages) != slowestN || len(s.SlowestTests) != slowestN || len(c.active) != 0 {
		t.Fatalf("slowest %d/%d, open packages %d", len(s.SlowestPackages), len(s.SlowestTests), len(c.active))
	}
}
