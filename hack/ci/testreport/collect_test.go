// A line that never ends keeps at most maxJoinedBytes in memory.
func TestPendingBound(t *testing.T) {
	t.Parallel()
	var p pending
	chunk := strings.Repeat("x", 1024)
	for i := 0; i < 3*maxJoinedBytes/len(chunk); i++ {
		p.add(chunk, false)
	}
	if len(p.buf) != maxJoinedBytes || p.dropped != 2*maxJoinedBytes || !p.open {
		t.Fatalf("buffer %d bytes, dropped %d", len(p.buf), p.dropped)
	}
	line, _, dropped := p.take()
	if len(line) != maxJoinedBytes || dropped != 2*maxJoinedBytes || p.open || len(p.buf) != 0 {
		t.Fatalf("take: %d bytes, dropped %d; after: open %v, %d bytes", len(line), dropped, p.open, len(p.buf))
	}
}

