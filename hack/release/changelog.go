package main

import (
	"fmt"
	"regexp"
	"strings"
)

// changelogHeader starts a new CHANGELOG.md. Release sections are inserted after it, newest first.
const changelogHeader = `# Changelog

All notable changes to Patrol CD are listed here, newest first. The file is generated by
` + "`hack/release`" + ` from the conventional commit subjects on ` + "`main`" + ` (guide:
[docs/guides/releasing.md](docs/guides/releasing.md)); edit a section in the release pull request
when a line needs rewording. Versions follow [semantic versioning](https://semver.org); before
1.0.0 a breaking change bumps the minor version.
`

// section groups commit types under one heading, in this order. Types not listed (docs, test,
// chore, ci, build, refactor, style) are left out.
var sections = []struct{ Title, Type string }{
	{"Features", "feat"},
	{"Bug fixes", "fix"},
	{"Performance", "perf"},
	{"Reverts", "revert"},
}

// releaseInfo is what a changelog section is rendered from.
type releaseInfo struct {
	Version  version
	Previous string // previous tag, "" for the first release
	Date     string // YYYY-MM-DD
	RepoURL  string // https://github.com/owner/repo, "" for no links
	Commits  []commit
}

// renderSection renders the "## [X.Y.Z](compare) - date" section of a release.
func renderSection(r releaseInfo) string {
	var b strings.Builder
	title := "[" + r.Version.String() + "]"
	switch {
	case r.RepoURL != "" && r.Previous != "":
		title += "(" + r.RepoURL + "/compare/" + r.Previous + "..." + r.Version.Tag() + ")"
	case r.RepoURL != "":
		title += "(" + r.RepoURL + "/releases/tag/" + r.Version.Tag() + ")"
	}
	fmt.Fprintf(&b, "## %s - %s\n", title, r.Date)

	var breaking []commit
	for _, c := range r.Commits {
		if c.Type != "" && c.Breaking {
			breaking = append(breaking, c)
		}
	}
	if len(breaking) > 0 {
		b.WriteString("\n### Breaking changes\n\n")
		for _, c := range breaking {
			b.WriteString(entry(c, r.RepoURL))
			if c.BreakingNote != "" {
				b.WriteString("  " + escapeMarkdown(c.BreakingNote) + "\n")
			}
		}
	}
	empty := true
	for _, s := range sections {
		var lines []string
		for _, c := range r.Commits {
			if c.Type == s.Type {
				lines = append(lines, entry(c, r.RepoURL))
			}
		}
		if len(lines) == 0 {
			continue
		}
		empty = false
		fmt.Fprintf(&b, "\n### %s\n\n%s", s.Title, strings.Join(lines, ""))
	}
	if empty && len(breaking) == 0 {
		b.WriteString("\nNo user-facing changes.\n")
	}
	return b.String()
}

// entry is one list item: "- **scope:** description (#PR) (sha)".
func entry(c commit, repoURL string) string {
	var b strings.Builder
	b.WriteString("- ")
	if c.Scope != "" {
		b.WriteString("**" + escapeMarkdown(c.Scope) + ":** ")
	}
	b.WriteString(escapeMarkdown(c.Desc))
	short := c.SHA
	if len(short) > 7 {
		short = short[:7]
	}
	if repoURL != "" {
		if c.PR > 0 {
			fmt.Fprintf(&b, " ([#%d](%s/pull/%d))", c.PR, repoURL, c.PR)
		}
		fmt.Fprintf(&b, " ([%s](%s/commit/%s))", short, repoURL, c.SHA)
	} else {
		if c.PR > 0 {
			fmt.Fprintf(&b, " (#%d)", c.PR)
		}
		fmt.Fprintf(&b, " (%s)", short)
	}
	b.WriteString("\n")
	return b.String()
}

// escapeMarkdown neutralizes what a commit subject (untrusted input) could use to inject markup
// into the changelog, the release notes and the pull request body: HTML, control characters and
// line breaks. Backticks, emphasis and links stay, as authors use them on purpose.
func escapeMarkdown(s string) string {
	s = strings.Map(func(r rune) rune {
		if r < 0x20 || r == 0x7f {
			return ' '
		}
		return r
	}, s)
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(s)
}

// sectionRe matches the heading of a release section and captures its version.
var sectionRe = regexp.MustCompile(`(?m)^## \[(\d+\.\d+\.\d+)\]`)

// insertSection returns the changelog with section added before the newest release, replacing an
// existing section of the same version. An empty changelog gets the standard header.
func insertSection(changelog, section string, v version) string {
	if strings.TrimSpace(changelog) == "" {
		changelog = changelogHeader
	}
	if start, end, ok := findSection(changelog, v); ok {
		return changelog[:start] + section + "\n" + changelog[end:]
	}
	if loc := sectionRe.FindStringIndex(changelog); loc != nil {
		return changelog[:loc[0]] + section + "\n" + changelog[loc[0]:]
	}
	return strings.TrimRight(changelog, "\n") + "\n\n" + section
}

// findSection returns the byte range of version v's section (heading to the next section or the
// end of the file).
func findSection(changelog string, v version) (start, end int, ok bool) {
	locs := sectionRe.FindAllStringSubmatchIndex(changelog, -1)
	for i, loc := range locs {
		if changelog[loc[2]:loc[3]] != v.String() {
			continue
		}
		end = len(changelog)
		if i+1 < len(locs) {
			end = locs[i+1][0]
		}
		return loc[0], end, true
	}
	return 0, 0, false
}

// sectionNotes returns the body of version v's section without its heading, for release notes.
func sectionNotes(changelog string, v version) (string, bool) {
	start, end, ok := findSection(changelog, v)
	if !ok {
		return "", false
	}
	body := changelog[start:end]
	if i := strings.IndexByte(body, '\n'); i >= 0 {
		body = body[i+1:]
	} else {
		body = ""
	}
	return strings.TrimSpace(body) + "\n", true
}
