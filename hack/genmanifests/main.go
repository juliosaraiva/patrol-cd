// Command genmanifests generates the static install manifests in deploy/manifests from the Helm
// chart deploy/helm/patrol-cd, so that Helm and non-Helm installations run the same objects.
//
// For every variant (install, namespace-install, core-install, HA, each with and without the
// source hydrator) it runs `helm template` with the fixed release name and namespace "patrol"
// and the variant's value files (deploy/manifests/profiles), removes the Helm-only metadata
// (helm.sh/chart, app.kubernetes.io/managed-by: Helm, helm.sh/* annotations; hooks and Secrets
// with data are refused), orders the objects for kubectl apply and writes:
//
//   - kustomize bases: namespace/ (the namespace with Pod Security labels), crds/ (CRDs and the
//     Operation admission policy) and one directory per variant (cluster-install/, ...,
//     ha/namespace-install-with-hydrator/) holding the variant's other objects;
//   - single-file manifests (install.yaml, ..., ha/install.yaml, crds.yaml): `kustomize build`
//     of the corresponding base with a header comment, so a base and its file never differ.
//
// Every run checks that each single-file manifest holds exactly the objects of its chart
// render (parsed independently, with the Helm metadata removed) and nothing else but the
// namespace, and that the order is kubectl-safe.
//
// Usage:
//
//	go run ./hack/genmanifests          # write the generated files
//	go run ./hack/genmanifests -check   # fail when a generated file is stale (write nothing)
//
// Tools: helm 4 (-helm or $HELM) and kustomize v5.8.1 (-kustomize or $KUSTOMIZE; `make tools`
// installs it into bin/). Helm runs with an empty, temporary configuration (no repositories,
// plugins or cache) and never contacts a cluster. Output is deterministic: the same inputs
// produce byte-identical files.
package main

